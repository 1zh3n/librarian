import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import {
  lstatSync, mkdirSync, readFileSync, renameSync, statSync, unlinkSync, writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const usage = "install-managed-runner --data-root ROOT --librarian-url URL [--unit-name NAME.service] [--unit-dir DIR]";
const marker = "# Generated by Librarian install-managed-runner";
const distribution = fileURLToPath(new URL("../../", import.meta.url));

function quote(value, executable = false) {
  if (/[\x00-\x1f\x7f]/.test(value)) throw new Error("Unit paths and URLs must be single-line values");
  const literal = value.replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("%", "%%");
  return '"' + (executable ? literal.split("$").join("$$") : literal) + '"';
}

function existing(path) {
  try { return lstatSync(path); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
}

function install(options) {
  const root = options["data-root"];
  if (!root || !isAbsolute(root) || !options["librarian-url"]) throw new Error(usage);
  if (!statSync(root).isDirectory()) throw new Error("Use the initialized Librarian data directory");
  const url = new URL(options["librarian-url"]);
  const local = ["127.0.0.1", "localhost", "[::1]"].includes(url.hostname);
  if ((url.protocol !== "https:" && !(url.protocol === "http:" && local)) ||
      url.username || url.password || url.href.includes("?") || url.href.includes("#")) {
    throw new Error("Use the Librarian HTTPS address or its local HTTP listener");
  }
  const unitName = options["unit-name"] ?? "librarian-managed-runner.service";
  if (!/^[A-Za-z0-9][A-Za-z0-9_.-]*\.service$/.test(unitName)) throw new Error("Invalid service name");
  const unitDir = options["unit-dir"] ?? join(process.env.XDG_CONFIG_HOME ?? join(homedir(), ".config"), "systemd/user");
  if (!isAbsolute(unitDir)) throw new Error("Use an absolute unit directory");
  const unitFile = join(unitDir, unitName);
  const prior = existing(unitFile);
  if (prior && (!prior.isFile() || !readFileSync(unitFile, "utf8").startsWith(marker + "\n"))) {
    throw new Error("The destination already contains another service definition");
  }
  const identity = join(resolve(root), ".librarian/managed-runner.json");
  const unit = [
    marker, "[Unit]", "Description=Librarian managed AI runner", "After=network.target", "",
    "[Service]", "Type=exec", "UMask=0077", "NoNewPrivileges=true", "Restart=on-failure", "RestartSec=5",
    `Environment=${quote("LIBRARIAN_URL=" + url.href)}`,
    `Environment=${quote("LIBRARIAN_RUNNER_IDENTITY_FILE=" + identity)}`,
    `ExecStart=${quote(join(distribution, "bin/node"), true)} ${quote(join(distribution, "bin/librarian/runner/runner.mjs"), true)}`,
    "", "[Install]", "WantedBy=default.target", "",
  ].join("\n");
  mkdirSync(unitDir, { recursive: true, mode: 0o700 });
  execFileSync(join(distribution, "librarian"), ["runner-enroll", "--data-root", root, "--identity-file", identity], {
    stdio: ["ignore", "ignore", "inherit"],
  });
  const info = lstatSync(identity);
  if (!info.isFile() || info.uid !== process.getuid() || (info.mode & 0o777) !== 0o600) {
    throw new Error("The enrolled identity must be a private file owned by this service account");
  }
  const stage = join(dirname(unitFile), "." + unitName + "." + randomUUID());
  try {
    writeFileSync(stage, unit, { flag: "wx", mode: 0o644 });
    renameSync(stage, unitFile);
  } finally {
    if (existing(stage)) unlinkSync(stage);
  }
  console.log(`Installed ${unitFile}\nsystemctl --user daemon-reload\nsystemctl --user enable --now ${unitName}`);
}

try {
  const { values } = parseArgs({ options: {
    "data-root": { type: "string" }, "librarian-url": { type: "string" },
    "unit-name": { type: "string" }, "unit-dir": { type: "string" }, help: { type: "boolean" },
  } });
  if (values.help) console.log(usage);
  else install(values);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
