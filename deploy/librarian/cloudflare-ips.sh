#!/usr/bin/env bash
# Fetch Cloudflare's published edge ranges and write the Caddy trusted-proxy
# environment file. Run as root on the deployment host.
#
# Usage:
#   cloudflare-ips.sh            # write /etc/librarian/cloudflare.env
#   cloudflare-ips.sh --print    # print the space-separated list only
#   cloudflare-ips.sh --apply    # write the file and add UFW allow rules
set -euo pipefail
umask 077

ENV_FILE="${LIBRARIAN_CLOUDFLARE_ENV:-/etc/librarian/cloudflare.env}"
PRINT=0
APPLY=0
for arg in "$@"; do
  case "$arg" in
    --print) PRINT=1 ;;
    --apply) APPLY=1 ;;
    -h|--help) sed -n '1,12p' "$0"; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

command -v curl >/dev/null || { echo "curl is required" >&2; exit 1; }

mapfile -t v4 < <(curl -fsSL --retry 3 https://www.cloudflare.com/ips-v4 | tr -d '\r')
mapfile -t v6 < <(curl -fsSL --retry 3 https://www.cloudflare.com/ips-v6 | tr -d '\r')
ranges=()
for range in "${v4[@]}" "${v6[@]}"; do
  [[ -n "$range" ]] || continue
  if [[ ! "$range" =~ ^[0-9a-fA-F:.]+/[0-9]{1,3}$ ]]; then
    echo "invalid Cloudflare range: $range" >&2
    exit 1
  fi
  ranges+=("$range")
done
if [[ ${#ranges[@]} -lt 10 ]]; then
  echo "unexpectedly few Cloudflare ranges: ${#ranges[@]}" >&2
  exit 1
fi
joined="${ranges[*]}"

if [[ "$PRINT" -eq 1 ]]; then
  printf '%s\n' "$joined"
  exit 0
fi

if [[ $EUID -ne 0 ]]; then
  echo "cloudflare-ips.sh must run as root unless --print is used" >&2
  exit 1
fi

install -d -m 0700 "$(dirname "$ENV_FILE")"
cat >"$ENV_FILE" <<EOF
# Generated by Librarian cloudflare-ips.sh. Re-run when Cloudflare changes ranges.
LIBRARIAN_TRUSTED_PROXIES="$joined"
CF_RANGES="$joined"
EOF
chmod 0600 "$ENV_FILE"

if [[ "$APPLY" -eq 1 ]]; then
  command -v ufw >/dev/null || { echo "ufw is required for --apply" >&2; exit 1; }
  for range in "${ranges[@]}"; do
    ufw allow from "$range" to any port 80 proto tcp >/dev/null
    ufw allow from "$range" to any port 443 proto tcp >/dev/null
  done
  echo "Added UFW rules for ${#ranges[@]} Cloudflare ranges; review stale rules with: ufw status"
fi

echo "Wrote $ENV_FILE with ${#ranges[@]} ranges."
